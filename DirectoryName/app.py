@st.cache_data
def load_data():
    """
    Reads comparison_results.csv produced by compare_performance.py
    Format: Metric, Baseline, Adaptive, Change, Change_Percent
    Returns flat dicts: baseline{}, edgeai{}, raw_df, source_label
    """

    # Metric name → internal key mapping (matches compare_performance.py output)
    METRIC_MAP = {
        'avg wait time (s)':        'avg_waiting_time',
        'avg waiting time (s)':     'avg_waiting_time',
        'median wait time (s)':     'median_wait_time',
        'median waiting time (s)':  'median_wait_time',
        'total wait time (s)':      'total_waiting_time',
        'total waiting time (s)':   'total_waiting_time',
        'avg time loss (s)':        'avg_time_loss',
        'avg timeloss (s)':         'avg_time_loss',
        'median time loss (s)':     'median_time_loss',
        'median timeloss (s)':      'median_time_loss',
        'total time loss (s)':      'total_time_loss',
        'avg duration (s)':         'avg_trip_duration',
        'avg trip duration (s)':    'avg_trip_duration',
        'median duration (s)':      'median_trip_duration',
        'std dev duration (s)':     'std_duration',
        'std dev wait time (s)':    'std_wait_time',
        'vehicle count':            'vehicle_count',
        'completed vehicles':       'vehicle_count',
        'total time loss (s)':      'total_time_loss',
    }

    csv_paths = [
        Path("comparison_results.csv"),
        Path("data/comparison_results.csv"),
    ]

    df = None
    source = "SAMPLE DATA"
    for p in csv_paths:
        if p.exists():
            df = pd.read_csv(p)
            source = f"CSV · {p.resolve()}"
            break

    baseline = {}
    edgeai = {}

    if df is not None:
        # Normalise column names
        df.columns = [c.strip() for c in df.columns]

        # Detect format A: Metric, Baseline, Adaptive, Change, Change_Percent
        if 'Metric' in df.columns and 'Baseline' in df.columns and 'Adaptive' in df.columns:
            for _, row in df.iterrows():
                metric_raw = str(row['Metric']).strip().lower()
                key = METRIC_MAP.get(metric_raw)
                if key:
                    try:
                        baseline[key] = float(row['Baseline'])
                        edgeai[key]   = float(row['Adaptive'])
                    except:
                        pass

        # Detect format B: system column (old format)
        elif 'system' in df.columns:
            try:
                b = df[df['system'].str.lower() == 'baseline'].iloc[0].to_dict()
                e_mask = df['system'].str.lower().isin(['edgeai', 'edge_ai', 'adaptive'])
                e = df[e_mask].iloc[0].to_dict()
                baseline = b
                edgeai   = e
            except:
                pass

    # If nothing loaded, use illustrative sample data
    if not baseline:
        source = "SAMPLE DATA (place comparison_results.csv next to app.py)"
        baseline = {
            'avg_waiting_time':  45.2,  'total_waiting_time': 12580.5,
            'median_wait_time':  36.1,  'avg_time_loss':      38.7,
            'median_time_loss':  30.4,  'total_time_loss':    10745.0,
            'avg_trip_duration': 185.3, 'median_trip_duration': 172.1,
            'std_duration':      42.1,  'std_wait_time':      18.3,
            'vehicle_count':     250,
        }
        edgeai = {
            'avg_waiting_time':  28.4,  'total_waiting_time': 7823.6,
            'median_wait_time':  22.3,  'avg_time_loss':      24.1,
            'median_time_loss':  19.8,  'total_time_loss':    6687.0,
            'avg_trip_duration': 152.9, 'median_trip_duration': 144.6,
            'std_duration':      28.7,  'std_wait_time':      12.1,
            'vehicle_count':     250,
        }

    return baseline, edgeai, source, df

