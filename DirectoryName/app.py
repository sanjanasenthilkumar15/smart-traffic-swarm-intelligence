def pct_imp(bv, ev, lower_better=True):
    """Return positive number = improvement"""
    if bv == 0: return 0.0
    raw = (ev - bv) / bv * 100
    return -raw if lower_better else raw

def fv(val, decimals=2, unit=""):
    try:
        v = float(val)
        if decimals == 0 or v == int(v):
            return f"{int(round(v))}{unit}"
        return f"{v:.{decimals}f}{unit}"
    except:
        return str(val)

